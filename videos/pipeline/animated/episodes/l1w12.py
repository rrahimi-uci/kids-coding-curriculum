def _stars(code: str) -> str:
    return ("import turtle\nt = turtle.Turtle()\nt.pensize(3)\nt.color(\"#0072B2\")\n"
            "t.penup()\nt.goto(-330, 30)\nt.pendown()\n" + code + "\nturtle.done()")


