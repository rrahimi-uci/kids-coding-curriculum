# What the program does: it prints four different lines in the Shell, and
# the last line is a goodbye that contains the word "bye".
# Key ideas: print() shows words on the screen, words go inside quotes, and
# Python runs the lines in order, from the top to the bottom.
# Approach: keep the first print() from the starter and add one print() for
# each TODO, in the same order as the starter.

# Lines that start with # are COMMENTS. Python skips them.
# Comments are notes for the people who read your code.

print("Hello, Python!")

# Who is coding today. A nickname keeps the child's real name private.
print("Today Captain Pixel is coding.")

# Favorite game or animal.
print("My favorite animal is the sea turtle.")

# Goodbye message. The checker looks for the word "bye" in the LAST line,
# so this print() must stay at the bottom.
print("Goodbye for now - bye!")

# Common mistakes children make here:
# - Typing Print or PRINT with a capital letter. Python only knows print.
